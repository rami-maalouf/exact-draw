import { chromium, expect } from '@playwright/test';
import { mkdir, mkdtemp, readFile, realpath, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { startService } from '../service/server';

const root = await realpath(await mkdtemp(join(tmpdir(), 'draw-lifecycle-e2e-')));
const service = await startService({ port: 0, stateDirectory: join(root, 'state') });
const base = `http://127.0.0.1:${service.server.port}`;
const call = async (route: string, body?: unknown) => {
  const response = await fetch(`${base}${route}`, { headers: { authorization: `Bearer ${service.token}`, 'content-type': 'application/json' }, ...(body === undefined ? {} : { method: 'POST', body: JSON.stringify(body) }) });
  if (!response.ok) throw new Error(await response.text());
  return response.json();
};
const build = Bun.spawn([process.execPath, 'scripts/build-editor.ts'], { stdout: 'inherit', stderr: 'inherit' });
if (await build.exited) throw new Error('Editor build failed');
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser', headless: true });
const page = await browser.newPage({ viewport: { width: 1200, height: 820 } });
await page.addInitScript(() => {
  const subscribe = EventSource.prototype.addEventListener;
  EventSource.prototype.addEventListener = function(type: string, ...args: any[]) {
    if (type !== 'command') return subscribe.call(this, type, ...args as [EventListener]);
  };
});
const errors: string[] = [];
page.on('pageerror', error => errors.push(error.message));
try {
  let path = join(root, 'First.excalidraw');
  await call('/api/lifecycle', { action: 'new', destination: path });
  await page.goto(`${base}/editor?token=${service.token}`);
  await expect(page.getByTestId('save-status')).toHaveText('Saved');
  const menu = async (name: string) => {
    await page.getByTestId('main-menu-trigger').click();
    await page.getByText(name, { exact: true }).click();
  };
  await menu('Version history');
  await expect(page.getByRole('dialog', { name: 'Version history' })).toBeVisible();
  await expect(page.getByRole('img', { name: 'Version preview' })).toBeVisible();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await menu('Rename drawing…');
  await page.getByRole('textbox', { name: 'Drawing name' }).fill('Unfinished name');
  await call('/api/command', { action: 'history' });
  await page.waitForTimeout(1500);
  await expect(page.getByRole('dialog', { name: 'Rename drawing', exact: true })).toBeVisible();
  await expect(page.getByRole('textbox', { name: 'Drawing name' })).toHaveValue('Unfinished name');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Version history', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByTestId('toolbar-rectangle').locator('..').click();
  const canvas = page.locator('canvas.excalidraw__canvas.interactive');
  const box = (await canvas.boundingBox())!;
  await page.mouse.move(box.x + 300, box.y + 220); await page.mouse.down();
  await page.mouse.move(box.x + 480, box.y + 350, { steps: 8 }); await page.mouse.up();
  // immediately rename to prove pending autosave is flushed before the filesystem move.
  await menu('Rename drawing…');
  await page.getByRole('textbox', { name: 'Drawing name' }).fill('Renamed');
  await page.getByRole('button', { name: 'Rename', exact: true }).click();
  path = join(root, 'Renamed.excalidraw');
  await expect(page.getByTestId('active-path')).toHaveText(path);
  expect(JSON.parse(await readFile(path, 'utf8')).elements).toHaveLength(1);
  await menu('Rename drawing…');
  await page.getByRole('textbox', { name: 'Drawing name' }).fill('RENAMED');
  await page.getByRole('button', { name: 'Rename', exact: true }).click();
  await expect(page.getByTestId('active-path')).toHaveText(join(root, 'RENAMED.excalidraw'));
  await menu('Rename drawing…');
  await page.getByRole('textbox', { name: 'Drawing name' }).fill('Renamed');
  await page.getByRole('button', { name: 'Rename', exact: true }).click();
  await expect(page.getByTestId('active-path')).toHaveText(path);
  await menu('Version history');
  const versions = page.locator('.history-version');
  await expect.poll(() => versions.count()).toBeGreaterThanOrEqual(2);
  await versions.last().click();
  await expect(page.getByRole('button', { name: 'Restore this version' })).toBeEnabled();
  await mkdir(join(import.meta.dir, '../.exact/screenshots'), { recursive: true });
  await page.screenshot({ path: join(import.meta.dir, '../.exact/screenshots/version-history.png') });
  await page.getByRole('button', { name: 'Restore this version' }).click();
  await expect.poll(async () => JSON.parse(await readFile(path, 'utf8')).elements.length).toBe(0);
  await menu('Duplicate drawing');
  const copy = join(root, 'Renamed copy.excalidraw');
  await expect(page.getByTestId('active-path')).toHaveText(copy);
  await menu('Move to Trash…');
  await page.getByRole('button', { name: 'Move to Trash', exact: true }).click();
  await expect(page.getByTestId('active-path')).toHaveText('');
  expect(await Bun.file(copy).exists()).toBe(false);
  // the shell's Trash command remains available when no drawing is open.
  await call('/api/command', { action: 'show-trash' });
  await expect(page.getByRole('dialog', { name: 'Trash', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Restore', exact: true }).click();
  await expect(page.getByTestId('active-path')).toHaveText(copy);
  await expect(page.getByText('Trash is empty.')).toBeVisible();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await menu('Close drawing');
  await expect(page.getByTestId('active-path')).toHaveText('');
  await call('/api/command', { action: 'reopen' });
  await expect(page.getByTestId('active-path')).toHaveText(copy);
  await page.reload();
  await expect(page.getByTestId('active-path')).toHaveText(copy);
  await menu('Version history');
  await page.setViewportSize({ width: 390, height: 720 });
  await expect(page.getByRole('dialog')).toBeVisible();
  expect(await page.getByRole('dialog').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: join(import.meta.dir, '../.exact/screenshots/version-history-narrow.png') });
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await rm(copy);
  await service.sync();
  await expect(page.getByRole('alert')).toContainText('autosave is paused');
  await call('/api/command', { action: 'open', destination: path });
  await expect(page.getByTestId('active-path')).toHaveText(path);
  const originalId = (await call('/api/document')).snapshot.id;
  const savedAs = join(root, 'Saved as.excalidraw');
  await call('/api/command', { action: 'save-as', destination: savedAs });
  await expect(page.getByTestId('active-path')).toHaveText(savedAs);
  const copyId = (await call('/api/document')).snapshot.id;
  expect(copyId).not.toBe(originalId);
  expect(await Bun.file(path).exists()).toBe(true);
  const moved = join(root, 'Moved.excalidraw');
  await call('/api/command', { action: 'move', destination: moved });
  await expect(page.getByTestId('active-path')).toHaveText(moved);
  expect((await call('/api/document')).snapshot.id).toBe(copyId);
  expect(await Bun.file(savedAs).exists()).toBe(false);
  await call('/api/command', { action: 'trash' });
  await page.getByRole('button', { name: 'Move to Trash', exact: true }).click();
  await expect(page.getByTestId('active-path')).toHaveText('');
  const occupied = JSON.stringify({ type: 'excalidraw', version: 2, elements: [], appState: { name: 'occupying file' }, files: {} });
  await Bun.write(moved, occupied);
  await call('/api/command', { action: 'show-trash' });
  await page.getByRole('button', { name: 'Restore', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('already exists');
  await page.getByText('Restore to another location', { exact: true }).click();
  const restoredElsewhere = join(root, 'Restored elsewhere.excalidraw');
  await page.getByRole('textbox', { name: 'Restore destination for Moved' }).fill(restoredElsewhere);
  await page.getByRole('button', { name: 'Restore here', exact: true }).click();
  await expect(page.getByTestId('active-path')).toHaveText(restoredElsewhere);
  expect((await call('/api/document')).snapshot.id).toBe(copyId);
  expect(await Bun.file(moved).text()).toBe(occupied);
  expect(errors).toEqual([]);
  console.log('PASS: lifecycle, pending-edit flush, version preview/restore, trash/recovery and reopen through the editor UI');
} finally { await browser.close(); service.stop(); await rm(root, { recursive: true, force: true }); }

import { chromium, expect } from '@playwright/test';
import { mkdtemp, readFile, readdir, realpath, rename, rm, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { startService } from '../service/server';

const build = Bun.spawn([process.execPath, 'scripts/build-editor.ts'], { cwd: join(import.meta.dir, '..'), stdout: 'inherit', stderr: 'inherit' });
if (await build.exited) throw new Error('Editor build failed');
const root = await realpath(await mkdtemp(join(tmpdir(), 'exact-editor-')));
const path = join(root, 'Drawing.excalidraw');
await writeFile(path, JSON.stringify({ type: 'excalidraw', version: 2, source: 'test', elements: [], appState: { viewBackgroundColor: '#ffffff' }, files: {} }));
const service = await startService({ port: 0, stateDirectory: join(root, 'state') });
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser', headless: true });
const page = await browser.newPage({ viewport: { width: 1200, height: 820 } });
const errors: string[] = [];
page.on('pageerror', error => errors.push(error.message));
const screenshots = join(import.meta.dir, '../.exact/screenshots');
await mkdir(screenshots, { recursive: true });
try {
  await service.open(path);
  await page.goto(`http://127.0.0.1:${service.server.port}/editor?token=${service.token}`);
  await expect(page.getByTestId('save-status')).toHaveText('Saved');
  await page.screenshot({ path: join(screenshots, 'editor-initial.png') });
  await page.getByTestId('toolbar-rectangle').locator('..').click();
  const canvas = page.locator('canvas.excalidraw__canvas.interactive');
  await expect(canvas).toBeVisible();
  const box = await canvas.boundingBox();
  if (!box) throw new Error('Canvas has no bounds');
  await page.mouse.move(box.x + 350, box.y + 220);
  await page.mouse.down();
  await page.mouse.move(box.x + 530, box.y + 340, { steps: 12 });
  await page.mouse.up();
  await expect.poll(async () => JSON.parse(await readFile(path, 'utf8')).elements.length).toBe(1);
  await expect(page.getByTestId('save-status')).toHaveText('Saved');
  const original = JSON.parse(await readFile(path, 'utf8'));
  expect(original.elements[0].type).toBe('rectangle');
  console.log('PASS: drawing gesture autosaved to the real file');
  const updated = { ...original, elements: [...original.elements, { ...original.elements[0], id: 'external-shape', x: original.elements[0].x + 250, backgroundColor: '#ff8787', fillStyle: 'solid' }] };
  await writeFile(`${path}.swap`, JSON.stringify(updated));
  await rename(`${path}.swap`, path);
  await expect(page.getByTestId('save-status')).toHaveText('Saved');
  await expect.poll(async () => page.locator('canvas.excalidraw__canvas.static').evaluate((canvas: HTMLCanvasElement) => { const ctx=canvas.getContext('2d')!; const pixels=ctx.getImageData(0,0,canvas.width,canvas.height).data; let red=0;for(let i=0;i<pixels.length;i+=4)if(pixels[i]>230&&pixels[i+1]>100&&pixels[i+1]<170&&pixels[i+2]>100&&pixels[i+2]<170)red++;return red; })).toBeGreaterThan(1000);
  await page.screenshot({ path: join(screenshots, 'editor-external-update.png') });
  await page.keyboard.press('Escape');
  await page.getByTestId('toolbar-rectangle').locator('..').click();
  await page.mouse.move(box.x + 350, box.y + 430);
  await page.mouse.down();
  await page.mouse.move(box.x + 460, box.y + 500, { steps: 8 });
  await page.mouse.up();
  await expect.poll(async () => JSON.parse(await readFile(path, 'utf8')).elements.length).toBe(3);
  console.log('PASS: external replacement loaded before the next autosave; both external and local shapes preserved');
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  const zoom = await page.getByRole('button', { name: 'Reset zoom', exact: true }).textContent();
  const third = JSON.parse(await readFile(path, 'utf8'));
  third.elements[0].strokeColor = '#1971c2';
  await writeFile(path, JSON.stringify(third));
  await expect.poll(async () => page.locator('canvas.excalidraw__canvas.static').evaluate((canvas: HTMLCanvasElement) => {
    const pixels = canvas.getContext('2d')!.getImageData(0, 0, canvas.width, canvas.height).data;
    let blue = 0; for (let i = 0; i < pixels.length; i += 4) if (pixels[i] < 70 && pixels[i + 1] > 70 && pixels[i + 1] < 160 && pixels[i + 2] > 140) blue++;
    return blue;
  })).toBeGreaterThan(30);
  await expect(page.getByRole('button', { name: 'Reset zoom', exact: true })).toHaveText(zoom!);
  console.log('PASS: external refresh preserves zoom');
  await page.route('**/api/save', route => route.abort());
  await page.getByTestId('toolbar-rectangle').locator('..').click();
  await page.mouse.move(box.x + 700, box.y + 430); await page.mouse.down();
  await page.mouse.move(box.x + 780, box.y + 500, { steps: 3 }); await page.mouse.up();
  await expect.poll(async () => page.evaluate(path => JSON.parse(localStorage.getItem(`exact-draw-draft:${path}`) ?? 'null')?.document.elements.length, path)).toBe(4);
  expect(JSON.parse(await readFile(path, 'utf8')).elements.length).toBe(3);
  await page.reload();
  await page.unroute('**/api/save');
  const retry = page.getByRole('button', { name: 'Retry', exact: true });
  if (await retry.isVisible()) await retry.click();
  await expect.poll(async () => JSON.parse(await readFile(path, 'utf8')).elements.length).toBe(4);
  await expect(page.getByTestId('save-status')).toHaveText('Saved');
  console.log('PASS: immediate page reload preserves the pending draft');
  const draw = async (offset: number) => {
    await page.getByTestId('toolbar-rectangle').locator('..').click();
    await page.mouse.move(box.x + 560 + offset, box.y + 320);
    await page.mouse.down(); await page.mouse.move(box.x + 610 + offset, box.y + 370, { steps: 3 }); await page.mouse.up();
  };
  await page.route('**/api/save', async route => { await route.fetch(); await route.abort(); }, { times: 1 });
  await draw(0);
  await expect.poll(async () => JSON.parse(await readFile(path, 'utf8')).elements.length).toBe(5);
  await expect(page.getByTestId('save-status')).toHaveText('Saved');
  console.log('PASS: lost save response reconciles the successful disk write without a false conflict');

  await page.route('**/api/save', route => route.abort());
  await draw(70);
  await expect.poll(async () => page.evaluate(path => JSON.parse(localStorage.getItem(`exact-draw-draft:${path}`) ?? 'null')?.document.elements.length, path)).toBe(6);
  const disk = JSON.parse(await readFile(path, 'utf8'));
  disk.appState.viewBackgroundColor = '#f8f9fa';
  await writeFile(path, JSON.stringify(disk)); await service.sync();
  await expect(page.getByTestId('save-status')).toHaveText('Conflict');
  await expect(page.getByRole('alert')).toContainText('Your edits are safe');
  const recoveries = await readdir(join(root, 'state/recovery'));
  const recoveryCounts = await Promise.all(recoveries.filter(name => !name.includes('.previous.')).map(async name => JSON.parse(await readFile(join(root, 'state/recovery', name), 'utf8')).elements.length));
  expect(recoveryCounts).toContain(6);
  expect(JSON.parse(await readFile(path, 'utf8')).elements.length).toBe(5);
  await page.getByRole('button', { name: 'Use disk version', exact: true }).click();
  await expect(page.getByTestId('save-status')).toHaveText('Saved');
  await page.unroute('**/api/save');
  console.log('PASS: dirty external overlap preserves recovery and never overwrites the newer disk file');

  await writeFile(path, '{'); await service.sync();
  await expect(page.getByRole('alert')).toContainText('autosave is paused');
  expect(await readFile(path, 'utf8')).toBe('{');
  await writeFile(path, JSON.stringify(disk)); await service.sync();
  await expect(page.getByTestId('save-status')).toHaveText('Saved');
  console.log('PASS: incomplete external JSON pauses autosave and recovers when the file is valid');

  await page.route('**/api/save', route => route.abort());
  await draw(140);
  await expect.poll(async () => page.evaluate(path => JSON.parse(localStorage.getItem(`exact-draw-draft:${path}`) ?? 'null')?.document.elements.length, path)).toBe(6);
  await rename(path, `${path}.moved`);
  const replacement = join(root, 'Another.excalidraw');
  await writeFile(replacement, JSON.stringify({ ...disk, elements: [] }));
  await page.unroute('**/api/save');
  await service.open(replacement);
  await expect(page.getByTestId('save-status')).toHaveText('Conflict');
  await expect(page.getByRole('alert')).toContainText('Your edits are safe');
  await page.getByRole('button', { name: 'Use disk version', exact: true }).click();
  await expect(page.getByTestId('active-path')).toHaveText(replacement);
  await expect(page.getByTestId('save-status')).toHaveText('Saved');
  console.log('PASS: a moved dirty drawing can be recovered before switching to another file');
  expect(errors).toEqual([]);
  await page.screenshot({ path: join(screenshots, 'editor-saved.png') });
} finally { await browser.close(); service.stop(); await rm(root, { recursive: true, force: true }); }
